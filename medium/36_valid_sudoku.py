def isValidSudoku(board):
    rows = []
    cols = []
    squares = []

    for i in range(9):
        rows.append(set())
        cols.append(set())
        squares.append(set())


    for row in range(9):
        for col in range(9):

            num = board[row][col]

            if num != ".":

                # get index of square
                sq = None

                if row < 3:
                    if col < 3:
                        sq = 0
                    elif col < 6:
                        sq = 1
                    else:
                        sq = 2
                elif row < 6:
                    if col < 3:
                        sq = 3
                    elif col < 6:
                        sq = 4
                    else:
                        sq = 5
                else:
                    if col < 3:
                        sq = 6
                    elif col < 6:
                        sq = 7
                    else:
                        sq = 8

                if num in rows[row] or num in cols[col] or num in squares[sq]:
                    return False
                else:
                    rows[row].add(num)
                    cols[col].add(num)
                    squares[sq].add(num)

    return True


